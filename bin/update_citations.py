#!/usr/bin/env python3
"""Update _data/citations.yml with Google Scholar citation counts.

Google Scholar blocks requests from GitHub Actions servers, so the citation
badges on the publications page read their numbers from _data/citations.yml
instead of fetching them during the build. Run this script on your own computer
from time to time, then commit and push the updated _data/citations.yml:

    python bin/update_citations.py

Only the Python standard library is used. The Scholar user id is read from
_data/socials.yml (scholar_userid).
"""

import datetime
import html
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOCIALS = os.path.join(ROOT, "_data", "socials.yml")
OUTPUT = os.path.join(ROOT, "_data", "citations.yml")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"

ROW = re.compile(r'<tr class="gsc_a_tr">(.*?)</tr>', re.S)
ARTICLE = re.compile(r"citation_for_view=[^:\"&]+:([^\"&]+)")
TITLE = re.compile(r'class="gsc_a_at">(.*?)</a>', re.S)
COUNT = re.compile(r'class="gsc_a_ac gs_ibl">([\d,]*)</a>')


def scholar_userid():
    with open(SOCIALS, encoding="utf-8") as f:
        m = re.search(r"^scholar_userid:\s*([^\s#]+)", f.read(), re.M)
    if not m:
        sys.exit("scholar_userid not found in _data/socials.yml")
    return m.group(1)


def parse(page):
    papers = []
    for row in ROW.findall(page):
        a, t = ARTICLE.search(row), TITLE.search(row)
        if not a:
            continue
        c = COUNT.search(row)
        count = int(c.group(1).replace(",", "")) if c and c.group(1) else 0
        papers.append((a.group(1), count, html.unescape(t.group(1)) if t else ""))
    return papers


def fetch(user):
    papers, start = [], 0
    while True:
        url = f"https://scholar.google.com/citations?user={user}&hl=en&cstart={start}&pagesize=100"
        req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept-Language": "en"})
        with urllib.request.urlopen(req, timeout=30) as r:
            page = r.read().decode("utf-8", "replace")
        batch = parse(page)
        if not batch and start == 0:
            sys.exit("No papers found - Google Scholar may have shown a CAPTCHA. Open the profile in a browser, then retry.")
        papers += batch
        if len(batch) < 100:
            return papers
        start += 100


def main():
    papers = fetch(scholar_userid())
    lines = [
        "# Google Scholar citation counts used by the publication badges.",
        "# Generated by bin/update_citations.py - rerun it to refresh, then commit this file.",
        f"updated: {datetime.date.today().isoformat()}",
        "papers:",
    ]
    for article_id, count, title in papers:
        lines.append(f'  "{article_id}": {count} # {title[:70]}')
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(papers)} papers to {os.path.relpath(OUTPUT, ROOT)}")


if __name__ == "__main__":
    main()
